import { createHash } from 'node:crypto'
import { readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import { defineConfig, type Plugin } from 'vite'
import react from '@vitejs/plugin-react'

/** Every file under a folder, as paths relative to it ("img/xxx.webp"). */
function listFiles(dir: string, base = dir): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) return listFiles(path, base)
    return name.startsWith('.') ? [] : [relative(base, path).split('\\').join('/')]
  })
}

/**
 * Writes sw.js at build time: a service worker that stores the whole app
 * (code, data, images) on the device, so it works without a connection.
 * The cache name changes with every build, which makes devices pick up updates.
 */
function offlineServiceWorker(): Plugin {
  return {
    name: 'offline-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const publicDir = join(import.meta.dirname, 'public')
      const publicFiles = listFiles(publicDir)
      const files = ['./', ...Object.keys(bundle).filter((f) => f !== 'index.html'), ...publicFiles]

      const hash = createHash('sha256')
      for (const file of Object.values(bundle)) hash.update(file.fileName).update(file.type === 'chunk' ? file.code : file.source)
      for (const file of publicFiles) {
        const { size, mtimeMs } = statSync(join(publicDir, file))
        hash.update(`${file}:${size}:${mtimeMs}`)
      }
      const version = hash.digest('hex').slice(0, 12)

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Generated by vite.config.ts — do not edit.
const CACHE = 'permis-b-${version}'
const FILES = ${JSON.stringify(files)}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(FILES))
      .then(() => self.skipWaiting()),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('permis-b-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url)
  if (event.request.method !== 'GET' || url.origin !== self.location.origin) return
  event.respondWith(
    // ignoreVary: some hosts answer with "Vary: Origin", which would hide the stored copy from scripts and styles.
    caches
      .match(event.request, { ignoreSearch: true, ignoreVary: true })
      .then((cached) => cached ?? fetch(event.request)),
  )
})
`,
      })
    },
  }
}

// Relative base so the build works from any sub-path (GitLab/GitHub Pages).
export default defineConfig({
  base: './',
  plugins: [react(), offlineServiceWorker()],
})
